// Generates the installer's file associations (spike S4): the app becomes an "Open with" candidate and a choice in
// Windows' Default apps for every type in media-extensions.json, without taking any type's default away from the
// player the person already uses. Uninstalling removes exactly what was added.
// Usage: node scripts/installer/gen-hooks.ts  (rewrites apps/player/src-tauri/windows/hooks*.nsh)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface MediaLists {
  audio: string[];
  video: string[];
}

export interface HookTarget {
  /** The product name, as Tauri installs it. */
  app: string;
  /** The ProgID prefix: one per installable build, so a test build never removes the real one's entries. */
  progId: string;
  file: string;
}

export const TARGETS: HookTarget[] = [
  { app: 'Pastel Media Pro', progId: 'PastelMediaPro', file: 'hooks.nsh' },
  { app: 'Pastel Media Pro Test', progId: 'PastelMediaProTest', file: 'hooks.test.nsh' },
];

const tauriDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'apps', 'player', 'src-tauri');

export function readLists(): MediaLists {
  return JSON.parse(readFileSync(join(tauriDir, 'media-extensions.json'), 'utf8')) as MediaLists;
}

/** The NSIS hook file for one build. */
export function buildHooks(lists: MediaLists, { app, progId }: HookTarget): string {
  const cap = `Software\\${app}\\Capabilities`;
  let post = '';
  let pre = '';
  for (const [group, exts] of [['Audio', lists.audio], ['Video', lists.video]] as const) {
    const id = `${progId}.${group}`;
    post += `  WriteRegStr SHCTX "Software\\Classes\\${id}" "" "${app} ${group.toLowerCase()}"\n`;
    post += `  WriteRegStr SHCTX "Software\\Classes\\${id}\\DefaultIcon" "" "$INSTDIR\\\${MAINBINARYNAME}.exe,0"\n`;
    post += `  WriteRegStr SHCTX "Software\\Classes\\${id}\\shell\\open" "" "Open with ${app}"\n`;
    post += `  WriteRegStr SHCTX "Software\\Classes\\${id}\\shell\\open\\command" "" '"$INSTDIR\\\${MAINBINARYNAME}.exe" "%1"'\n`;
    pre += `  DeleteRegKey SHCTX "Software\\Classes\\${id}"\n`;
    for (const e of exts) {
      // A candidate under the type, never its default: the person's own choice stays.
      post += `  WriteRegStr SHCTX "Software\\Classes\\.${e}\\OpenWithProgids" "${id}" ""\n`;
      post += `  WriteRegStr SHCTX "${cap}\\FileAssociations" ".${e}" "${id}"\n`;
      pre += `  DeleteRegValue SHCTX "Software\\Classes\\.${e}\\OpenWithProgids" "${id}"\n`;
    }
  }
  return `; Generated by scripts/installer/gen-hooks.ts from media-extensions.json. Don't edit by hand.
; "Open with" and Default apps for ${app}, without changing any file type's default (spike S4).
!macro NSIS_HOOK_POSTINSTALL
  WriteRegStr SHCTX "${cap}" "ApplicationName" "${app}"
  WriteRegStr SHCTX "${cap}" "ApplicationDescription" "A local media player for music and video"
  WriteRegStr SHCTX "Software\\RegisteredApplications" "${app}" "${cap}"
${post}  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
!macroend

!macro NSIS_HOOK_PREUNINSTALL
${pre}  DeleteRegValue SHCTX "Software\\RegisteredApplications" "${app}"
  DeleteRegKey SHCTX "Software\\${app}"
  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
!macroend
`;
}

export const hooksPath = (target: HookTarget) => join(tauriDir, 'windows', target.file);

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const lists = readLists();
  for (const t of TARGETS) {
    writeFileSync(hooksPath(t), buildHooks(lists, t));
    console.log(`${t.file} written`);
  }
}
